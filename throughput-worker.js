class ThroughputWorker {
    constructor() {
        this.buildingData = null;
        this.isCancelled  = false;
        self.addEventListener('message', this.handleMessage.bind(this));
    }

    handleMessage(e) {
        const { type, data, taskId } = e.data;
        if (type === 'init')   { this.buildingData = data.buildingData; return; }
        if (type === 'cancel') { this.isCancelled = true;  return; }
        if (type === 'start')  { this.isCancelled = false; this.startAnalysis(data, taskId); }
    }

    async startAnalysis(data, taskId) {
        try {
            const {
                txPosition, radius, resolution, frequency, txPower, environment,
                txHeight, bandwidth, cellLoad, useConservativeSinr,
                noiseFloor = -95, interferencedBm = -90
            } = data;

            const radiusSq    = radius * radius;
            const heightRange = radius * 0.3;
            const fcGHz       = frequency / 1000;
            const prbs        = BW_TO_PRBS[bandwidth] || 50;
            const prbIdx      = PRB_IDX[prbs] || (prbs - 1);

            // Pre-baked noise table
            const noise  = makeNoiseTable(8);
            let noiseIdx = 0;

            const xSteps = Math.ceil((radius * 2) / resolution);
            const zSteps = Math.ceil((radius * 2) / resolution);
            const ySteps = Math.ceil(heightRange  / resolution);
            const total  = xSteps * zSteps * ySteps;

            const posArr = new Float32Array(total * 3);
            const tpArr  = new Float32Array(total);
            const siArr  = new Float32Array(total);
            let ptCount = 0, ptsDone = 0;
            let totalTP = 0, maxTP = 0, minTP = Infinity;

            const CHUNK = 2000;

            for (let xi = 0; xi < xSteps; xi++) {
                const ox = -radius + xi * resolution;
                for (let zi = 0; zi < zSteps; zi++) {
                    const oz = -radius + zi * resolution;
                    for (let yi = 0; yi < ySteps; yi++) {
                        if (this.isCancelled) throw new Error('Analysis cancelled');

                        const y    = yi * resolution;
                        const dx2D = ox * ox + oz * oz;
                        const dy   = y - txPosition.y;
                        if (dx2D + dy * dy > radiusSq) { ptsDone++; continue; }

                        const d2D = Math.sqrt(dx2D);
                        const d3D = Math.sqrt(dx2D + dy * dy);
                        const rxPos = { x: txPosition.x + ox, y, z: txPosition.z + oz };

                        let pl = calcPathLoss(environment, d2D, d3D, fcGHz, txHeight, y);
                        if (this.buildingData) {
                            pl += calcBuildingPenetrationLoss(txPosition, rxPos, frequency, this.buildingData);
                        }
                        pl += noise[noiseIdx++ & (NOISE_TABLE_SIZE - 1)];

                        const rxPow = txPower - pl;
                        // SINR using per-point noise + interference (dBm linear combination avoided; use log approximation)
                        const noiseInterference = 10 * Math.log10(
                            Math.pow(10, noiseFloor / 10) + Math.pow(10, interferencedBm / 10)
                        );
                        let sinr = rxPow - noiseInterference;
                        if (useConservativeSinr) sinr -= 5;
                        sinr = Math.max(-10, Math.min(30, sinr));

                        const tp = this.calcThroughput(sinr, prbIdx, cellLoad);
                        if (isFinite(tp)) {
                            const base = ptCount * 3;
                            posArr[base]     = rxPos.x;
                            posArr[base + 1] = y;
                            posArr[base + 2] = rxPos.z;
                            tpArr[ptCount]   = tp;
                            siArr[ptCount]   = sinr;
                            ptCount++;
                            totalTP += tp;
                            if (tp > maxTP) maxTP = tp;
                            if (tp < minTP) minTP = tp;
                        }

                        ptsDone++;
                        if (ptsDone % CHUNK === 0 || ptsDone === total) {
                            self.postMessage({
                                type: 'progress',
                                progress: Math.min(100, Math.round((ptsDone / total) * 100)),
                                taskId,
                                data: { processed: ptsDone, total, throughputPoints: ptCount }
                            });
                            await yieldToEventLoop();
                        }
                    }
                }
            }

            const posTrim = posArr.slice(0, ptCount * 3);
            const tpTrim  = tpArr.slice(0, ptCount);
            const siTrim  = siArr.slice(0, ptCount);

            self.postMessage(
                { type: 'complete', taskId, data: {
                    positions: posTrim,
                    throughputs: tpTrim,
                    sinrs: siTrim,
                    pointCount: ptCount,
                    avgThroughput: ptCount > 0 ? totalTP / ptCount : 0,
                    maxThroughput: maxTP,
                    minThroughput: minTP === Infinity ? 0 : minTP,
                    pointsAnalyzed: ptsDone,
                    totalPoints: total
                }},
                [posTrim.buffer, tpTrim.buffer, siTrim.buffer]
            );

        } catch (err) {
            self.postMessage({ type: 'error', taskId, data: err.message });
        }
    }

    calcThroughput(sinr, prbIdx, cellLoad) {
        // Binary search over 16-entry table (faster than linear scan)
        let lo = 0, hi = SINR_TO_CQI.length - 1;
        while (lo <= hi) {
            const mid = (lo + hi) >> 1;
            const e   = SINR_TO_CQI[mid];
            if      (sinr < e.sinrMin) hi = mid - 1;
            else if (sinr >= e.sinrMax) lo = mid + 1;
            else { lo = mid; break; }
        }
        const cqiData = SINR_TO_CQI[lo];
        if (!cqiData || cqiData.cqi === 0 || !cqiData.tbsIndex) return 0;

        const tbsRow = TBS_TABLE[cqiData.tbsIndex];
        if (!tbsRow) return 0;
        const tbs = tbsRow[Math.min(prbIdx, tbsRow.length - 1)];
        if (!tbs) return 0;
        return (tbs * 1000 / 1000000) * cellLoad;
    }
}

function yieldToEventLoop() { return new Promise(r => setTimeout(r, 0)); }

